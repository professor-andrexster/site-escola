<p>O <strong>período de defeso</strong> é o intervalo de tempo em que a pesca de determinadas espécies de peixes é proibida por lei. No Brasil, essa proteção é estabelecida pelo Instituto Brasileiro do Meio Ambiente e dos Recursos Naturais Renováveis (IBAMA) e tem como objetivo garantir a reprodução dos peixes sem interferência humana.</p>

